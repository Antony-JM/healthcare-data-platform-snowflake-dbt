-- 02_raw_tables.sql
-- RAW preserves source-like values and adds ingestion lineage metadata.
-- No business transformations belong in RAW.

USE WAREHOUSE HEALTH_DW_WH;

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.PATIENTS (
    PATIENT_ID        VARCHAR,
    FIRST_NAME        VARCHAR,
    LAST_NAME         VARCHAR,
    DATE_OF_BIRTH     DATE,
    GENDER            VARCHAR,
    ADDRESS           VARCHAR,
    CITY              VARCHAR,
    COUNTRY           VARCHAR,
    POSTCODE          VARCHAR,
    PATIENT_TYPE      VARCHAR,
    CREATED_DATE      DATE,
    SOURCE_SYSTEM     VARCHAR,
    SOURCE_TABLE      VARCHAR,
    BATCH_ID          VARCHAR,
    FILE_NAME         VARCHAR,
    INGESTED_AT       TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.PROVIDERS (
    PROVIDER_ID       VARCHAR,
    PROVIDER_NAME     VARCHAR,
    SPECIALTY         VARCHAR,
    FACILITY          VARCHAR,
    SOURCE_SYSTEM     VARCHAR,
    SOURCE_TABLE      VARCHAR,
    BATCH_ID          VARCHAR,
    FILE_NAME         VARCHAR,
    INGESTED_AT       TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.INSURANCE (
    INSURANCE_ID      VARCHAR,
    PATIENT_ID        VARCHAR,
    PAYER_NAME        VARCHAR,
    POLICY_NUMBER     VARCHAR,
    EFFECTIVE_DATE    DATE,
    EXPIRY_DATE       DATE,
    STATUS            VARCHAR,
    SOURCE_SYSTEM     VARCHAR,
    SOURCE_TABLE      VARCHAR,
    BATCH_ID          VARCHAR,
    FILE_NAME         VARCHAR,
    INGESTED_AT       TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.APPOINTMENTS (
    APPOINTMENT_ID    VARCHAR,
