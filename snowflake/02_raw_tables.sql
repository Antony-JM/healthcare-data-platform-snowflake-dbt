    SOURCE_TABLE      VARCHAR,
    BATCH_ID          VARCHAR,
    FILE_NAME         VARCHAR,
    INGESTED_AT       TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.CLINICAL_RECORDS (
    CLINICAL_ID       VARCHAR,
    PATIENT_ID        VARCHAR,
