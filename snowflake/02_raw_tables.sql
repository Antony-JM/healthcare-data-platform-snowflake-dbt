    INGESTED_AT       TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.CLAIMS (
    CLAIM_ID          VARCHAR,
    PATIENT_ID        VARCHAR,
    PROVIDER_ID       VARCHAR,
    SERVICE_DATE      DATE,
    CLAIM_STATUS      VARCHAR,
    BILLED_AMOUNT     NUMBER(18,2),
    PAID_AMOUNT       NUMBER(18,2),
    BALANCE_AMOUNT    NUMBER(18,2),
    SOURCE_SYSTEM     VARCHAR,
    SOURCE_TABLE      VARCHAR,
    BATCH_ID          VARCHAR,
    FILE_NAME         VARCHAR,
    INGESTED_AT       TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DEV_HEALTH_DB.RAW.BILLING (
    BILLING_ID        VARCHAR,
